-- Password resets approved by an administrator instead of emailed links.
CREATE TABLE password_reset_requests (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    password_hash VARCHAR(255) NOT NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reason        TEXT,
    requested_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    reviewed_by   INTEGER REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at   TIMESTAMPTZ
);

-- At most one open request per account.
CREATE UNIQUE INDEX password_reset_requests_one_pending
    ON password_reset_requests (user_id) WHERE status = 'PENDING';
